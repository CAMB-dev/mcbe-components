"""Rebuild pixel control geometry as inline raster skins, recording source hashes.

Unmodified reference files stay in .cache. Skins are re-drawn from pixel runs.
Requires Pillow. Normal builds use the committed generated CSS.
"""
from pathlib import Path
from io import BytesIO
import base64
import hashlib
import json
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parent.parent
mapping = json.loads((root / 'scripts/classic-reference-map.json').read_text())
css = ['/* Generated by scripts/prepare-classic.py. See docs/FIDELITY.md. */', ':root {']
manifest = {}
for name, config in mapping.items():
    source = root / '.cache/references' / (config['file'] + '.png')
    image = Image.open(source).convert('RGBA')
    runs = []
    for y in range(image.height):
        x = 0
        while x < image.width:
            color = image.getpixel((x, y)); end = x + 1
            while end < image.width and image.getpixel((end, y)) == color:
                end += 1
            if color[3]:
                runs.append((x, y, end - 1, color))
            x = end
    # Use the same raster compositing path as the game reference, including
    # locked 50%-alpha states. SVG backgrounds round translucent colors differently.
    raster = Image.new('RGBA', image.size)
    drawing = ImageDraw.Draw(raster)
    for x, y, end, color in runs:
        drawing.rectangle((x, y, end, y), fill=color)
    output = BytesIO()
    raster.save(output, format='PNG', compress_level=9)
    uri = 'data:image/png;base64,' + base64.b64encode(output.getvalue()).decode()
    css.append(f'  --mc-skin-{name}: url("{uri}");')
    manifest[name] = {
        'source': 'resource_pack/textures/ui/' + config['file'] + '.png',
        'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'size': [image.width, image.height],
        'slice': config.get('slice'),
        **({'edge': config['edge']} if 'edge' in config else {}),
        'encoding': 'png',
    }
css.append('}')
(root / 'src/textures.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
(root / 'docs/classic-skins.json').write_text(json.dumps({
    'referenceCommit': '46ba6ea985fb5a92d79a9419198f10dda14c199d',
    'scale': 2,
    'skins': manifest,
}, indent=2) + '\n', encoding='utf-8')
print(f'Generated {len(mapping)} control skins and provenance manifest.')
