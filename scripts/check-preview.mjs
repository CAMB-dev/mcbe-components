import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';
await mkdir('.cache/preview', { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  page.on('requestfailed', request => failures.push(request.url()));
  page.on('response', response => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
  await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => {
    const renderers = [...document.querySelectorAll('[data-render-state]')];
    return renderers.length > 0 && renderers.every(node => node.getAttribute('data-render-state') === 'ready');
  });
  assert.match(await page.title(), /mcbeui/);
  assert.equal(await page.getByRole('button', { name: 'Create new world', exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Create new world', exact: true }).click();
  assert(await page.getByRole('dialog', { name: 'Create new world' }).isVisible());
  await page.screenshot({ path: '.cache/preview/dialog.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.cache/preview/mobile-dialog.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.keyboard.press('Escape');
  assert(!(await page.getByRole('dialog', { name: 'Create new world' }).isVisible()));
  await page.screenshot({ path: '.cache/preview/desktop.png' });
  await page.locator('#inputs').scrollIntoViewIfNeeded();
  const input = page.locator('#inputs').getByRole('textbox', { name: 'World name', exact: true });
  assert.equal(await input.evaluate(node => getComputedStyle(node).textShadow), 'rgb(63, 63, 63) 2px 2px 0px');
  await page.getByRole('combobox', { name: 'Difficulty' }).click();
  await page.screenshot({ path: '.cache/preview/inputs-combobox.png' });
  await page.keyboard.press('Escape');
  await page.locator('#input-states').screenshot({ path: '.cache/preview/input-states.png' });
  await page.locator('#surfaces').screenshot({ path: '.cache/preview/panel.png' });
  await page.locator('#feedback').screenshot({ path: '.cache/preview/progress.png' });
  await page.mouse.move(0, 0);
  await page.locator('#inventory-states').screenshot({ path: '.cache/preview/itemslot-rebuilt.png' });
  await page.locator('#inventory-states .slot-state-examples').getByRole('button', { name: /^Enchanted diamond sword/ }).hover();
  const itemTooltip = page.locator('.mc-item-tooltip');
  await itemTooltip.waitFor({ state: 'visible' });
  assert.equal(await itemTooltip.evaluate(node => getComputedStyle(node).boxSizing), 'border-box');
  assert.equal(await itemTooltip.innerText(), 'Enchanted diamond sword\nSharpness IV\nUnbreaking III');
  await itemTooltip.screenshot({ path: '.cache/preview/item-tooltip.png' });
  await page.mouse.move(0, 0);
  const glintExample = page.locator('#item-glint');
  const glintCanvases = glintExample.locator('canvas[data-renderer="item-glint"]');
  assert.equal(await glintCanvases.count(), 3);
  assert.deepEqual(await glintCanvases.evaluateAll(nodes => nodes.map(node => node.getAttribute('data-render-state'))), ['ready', 'ready', 'ready']);
  await glintExample.screenshot({ path: '.cache/preview/item-glint.png' });
  const initialGlint = await glintCanvases.first().evaluate(node => node.toDataURL());
  const glintPhase = glintExample.getByRole('slider', { name: 'Glint first-layer UV offset' });
  await glintPhase.focus();
  await glintPhase.press('ArrowRight');
  await page.waitForFunction(previous => {
    const canvas = document.querySelector('#item-glint canvas[data-renderer="item-glint"]');
    return canvas?.getAttribute('data-render-state') === 'ready' && canvas.toDataURL() !== previous;
  }, initialGlint);
  await glintExample.screenshot({ path: '.cache/preview/item-glint-controlled-phase.png' });
  await page.locator('#workstations').screenshot({ path: '.cache/preview/workstations.png' });
  await page.setViewportSize({ width: 1440, height: 2000 });
  await page.locator('#processing').screenshot({ path: '.cache/preview/processing.png' });
  await page.locator('#anvil').screenshot({ path: '.cache/preview/anvil.png' });
  await page.locator('#containers').screenshot({ path: '.cache/preview/containers.png' });
  for (const id of ['brewing','special-workstations','hud','scrolling','advanced-workstations','hud-overlays','settings','feedback-primitives','game-lists','settings-panel','loading-screen','achievement-toast','game-controls','trading-mounts','inventory-screens']) {
    await page.locator('#'+id).screenshot({ path: '.cache/preview/'+id+'.png' });
  }
  await page.setViewportSize({ width: 1100, height: 900 });
  const creative = page.locator('#inventory-screens .mc-creative-inventory');
  await creative.getByRole('tab', { name: 'Search', exact: true }).click();
  await creative.getByRole('searchbox', { name: 'Search creative inventory' }).fill('diamond');
  assert.equal(await creative.locator('.mc-creative-inventory__items .mc-slot').count(), 2);
  await page.mouse.move(0, 0);
  await page.locator('#inventory-screens .mc-creative-inventory-scroll').screenshot({ path: '.cache/preview/creative-search.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#typography').screenshot({ path: '.cache/preview/fonts-shadow.png' });
  assert.equal(await page.locator('.font-shadow-comparison .mc-text').first().evaluate(node=>getComputedStyle(node).textShadow), 'rgb(63, 63, 63) 2px 2px 0px');
  assert.equal(await page.locator('.font-shadow-comparison .mc-text').last().evaluate(node=>getComputedStyle(node).textShadow), 'none');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.cache/preview/mobile.png', fullPage: true });
  await page.locator('#inputs').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '.cache/preview/mobile-inputs.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(failures, []);
  const result = { status: 'PASS', target: 'production site/', errors: failures, font: await page.locator('.font-note').innerText(), itemGlint: { ready: 3, controlledPhaseChanged: true }, itemTooltip: { suppliedLoreOnly: true } };
  await writeFile('.cache/preview/result.json', JSON.stringify(result, null, 2));
  console.log(result);
} finally { await browser.close(); }
